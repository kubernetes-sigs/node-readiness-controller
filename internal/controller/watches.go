package controller

import (
	"context"
	"time"

	corev1 "k8s.io/api/core/v1"
	"k8s.io/apimachinery/pkg/types"
	"k8s.io/client-go/util/workqueue"
	ctrl "sigs.k8s.io/controller-runtime"
	"sigs.k8s.io/controller-runtime/pkg/client"
	"sigs.k8s.io/controller-runtime/pkg/event"
	"sigs.k8s.io/controller-runtime/pkg/reconcile"

	readinessv1alpha1 "sigs.k8s.io/node-readiness-controller/api/v1alpha1"
)

const (
	// defaultSummaryBatchPeriod is the default debounce window for node event triggers.
	// When hundreds of nodes change state concurrently (e.g. cluster-wide upgrades
	// or mass readiness transitions), incoming events are coalesced within this
	// duration into a single summary evaluation per rule, preventing etcd storms.
	defaultSummaryBatchPeriod = 2 * time.Second
)

// NodeToRulesMapFunc retrieves all NodeReadinessRules that apply to the given node.
type NodeToRulesMapFunc func(
	context.Context,
	*corev1.Node,
) []*readinessv1alpha1.NodeReadinessRule

// NodeToRuleEventHandler transforms Node watch events into Rule reconcile
// requests and enqueues them after a delay to debounce high-frequency bursts.
type NodeToRuleEventHandler struct {
	getApplicableRulesForNode NodeToRulesMapFunc
	delay                     time.Duration
}

// NewNodeToRuleEventHandler returns a new NodeToRuleEventHandler.
func NewNodeToRuleEventHandler(
	nodeToRulesMapFunc NodeToRulesMapFunc,
	delay time.Duration,
) *NodeToRuleEventHandler {
	return &NodeToRuleEventHandler{
		getApplicableRulesForNode: nodeToRulesMapFunc,
		delay:                     delay,
	}
}

// enqueue maps a node to applicable rule reconcile requests and enqueues
// them after the configured debounce delay.
func (h *NodeToRuleEventHandler) enqueue(
	ctx context.Context,
	obj client.Object,
	q workqueue.TypedRateLimitingInterface[reconcile.Request],
) {
	log := ctrl.LoggerFrom(ctx)
	node, ok := obj.(*corev1.Node)
	if !ok || node == nil {
		log.Error(nil, "Node event has no object")
		return
	}

	// Fetch rules matching this node from the controller's cache.
	rules := h.getApplicableRulesForNode(ctx, node)
	for _, rule := range rules {
		q.AddAfter(reconcile.Request{
			NamespacedName: types.NamespacedName{Name: rule.Name},
		}, h.delay)
	}
}

// Create handles Node creation events by mapping the Node to rule reconcile
// requests and enqueuing each after the debounce delay.
func (h *NodeToRuleEventHandler) Create(
	ctx context.Context,
	evt event.CreateEvent,
	q workqueue.TypedRateLimitingInterface[reconcile.Request],
) {
	h.enqueue(ctx, evt.Object, q)
}

// Update handles Node update events. Both new and old Node states are mapped
// so rules that gained or lost interest in this node are scheduled for reconciliation.
// The workqueue deduplicates entries, so queuing both states is completely safe.
func (h *NodeToRuleEventHandler) Update(
	ctx context.Context,
	evt event.UpdateEvent,
	q workqueue.TypedRateLimitingInterface[reconcile.Request],
) {
	h.enqueue(ctx, evt.ObjectNew, q)
	h.enqueue(ctx, evt.ObjectOld, q)
}

// Delete handles Node deletion events. Deleted nodes notify applicable rules
// so their status summaries decrement targeted counts.
func (h *NodeToRuleEventHandler) Delete(
	ctx context.Context,
	evt event.DeleteEvent,
	q workqueue.TypedRateLimitingInterface[reconcile.Request],
) {
	h.enqueue(ctx, evt.Object, q)
}

// Generic implements handler.EventHandler. Generic events are not generated by
// standard Kubernetes Node informers, but the method is required by the interface.
func (h *NodeToRuleEventHandler) Generic(
	_ context.Context,
	_ event.GenericEvent,
	_ workqueue.TypedRateLimitingInterface[reconcile.Request],
) {
	// No-op: standard Node watch streams only produce Create, Update, and Delete events.
}
